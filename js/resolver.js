  const SLOT_ORDER = ['A','B','D','E','G','I','K','L'];
  const SLOT_MATCH_ID = {"A": 79, "B": 85, "D": 81, "E": 74, "G": 82, "I": 77, "K": 87, "L": 80};
  /* ── Group-stage completeness & standings ──────────────────────────────
     A group is "final" once all 6 of its fixtures have a recorded result.
     Until then we don't promise a winner/runner-up/3rd, since the table
     could still change. */

  function _groupFixtures(letter) {
    return WC2026.FIXTURES.filter(f => f.stage === 'group' && f.group === letter);
  }

  function _isGroupFinal(letter) {
    return _groupFixtures(letter).every(f => {
      const ld = Live.forFixture(f);
      return ld && ld.scoreHome !== null && ld.status !== 'SCHEDULED' && ld.status !== 'TIMED';
    });
  }

  function _groupTable(letter) {
    // Standings.calcGroup already does live-score-aware sorting (pts, gd, gf, name)
    return Standings.calcGroup(letter);
  }

  // group letter -> {first, second, third} team names, only once that group is final
  let _groupResultCache = null;
  function _allGroupResults() {
    if (_groupResultCache) return _groupResultCache;
    const out = {};
    WC2026.groups.forEach(letter => {
      if (!_isGroupFinal(letter)) { out[letter] = null; return; }
      const table = _groupTable(letter);
      out[letter] = { first: table[0].team, second: table[1].team, third: table[2] ? table[2].team : null };
    });
    _groupResultCache = out;
    return out;
  }

  /* ── Best-3rd-place ranking across all 12 groups ───────────────────────
     Only meaningful once EVERY group has finished (FIFA only ranks/seeds
     3rd-placed teams after the full group stage concludes on June 27). */

  function _allGroupsFinal() {
    return WC2026.groups.every(_isGroupFinal);
  }

  function _thirdPlaceRanking() {
    if (!_allGroupsFinal()) return null;
    const rows = WC2026.groups.map(letter => {
      const table = _groupTable(letter);
      const r = table[2]; // 3rd place row from Standings.calcGroup
      return { group: letter, team: r.team, pts: r.pts, gd: r.gd, gf: r.gf };
    });
    rows.sort((a, b) => b.pts - a.pts || b.gd - a.gd || b.gf - a.gf || a.group.localeCompare(b.group));
    // NOTE: FIFA's real tiebreakers also include team conduct (cards) and
    // FIFA ranking, which this app has no data feed for. In the rare event
    // of a tie on points/GD/GF that those criteria would break, the slot
    // is left unresolved here rather than guessed.
    return rows;
  }

  // Returns { qualifyingGroups: ['B','C',...] sorted, slotMap: {A:'C', B:'G', ...} }
  // slotMap keys are the 8 fixed "winner-group" letters (A,B,D,E,G,I,K,L);
  // slotMap[letter] = the group whose 3rd-place team plays the winner of `letter`.
  // Returns null if not yet determinable (group stage incomplete, or a
  // genuine tie at the qualification cutoff that this app can't break).
  let _bestThirdCache;
  function _bestThirdSlots() {
    if (_bestThirdCache !== undefined) return _bestThirdCache;
    const ranking = _thirdPlaceRanking();
    if (!ranking) return (_bestThirdCache = null);

    // Tie at the 8th/9th cutoff this app can't resolve (needs cards/FIFA rank)
    if (ranking.length >= 9) {
      const r8 = ranking[7], r9 = ranking[8];
      if (r8.pts === r9.pts && r8.gd === r9.gd && r8.gf === r9.gf) return (_bestThirdCache = null);
    }

    const qualifying = ranking.slice(0, 8).map(r => r.group).sort();
    const row = ANNEX_C.find(([groups]) => groups.length === qualifying.length &&
      groups.every((g, i) => g === qualifying[i]));
    if (!row) return (_bestThirdCache = null); // shouldn't happen — defensive
    const [, slots] = row;
    const slotMap = {};
    SLOT_ORDER.forEach((winnerGroup, i) => { slotMap[winnerGroup] = slots[i]; });

    const teamByGroup = {};
    ranking.forEach(r => { teamByGroup[r.group] = r.team; });

    return (_bestThirdCache = { qualifying, slotMap, teamByGroup });
  }

  /* ── Fixture result lookup (works for ANY stage, group through final) ── */

  function _result(fixtureId) {
    const f = WC2026.FIXTURES.find(x => x.id === fixtureId);
    if (!f) return null;
    const ld = Live.forFixture(f);
    if (!ld || ld.scoreHome === null || ld.status === 'SCHEDULED' || ld.status === 'TIMED') return null;
    if (ld.status !== 'FINISHED') return null; // don't promote a winner mid-match
    return { fixture: f, ld };
  }

  // Returns the resolved *display name* (already i18n-translated team name)
  // of the winner/loser of a given match id, or null if not finished yet.
  //
  // IMPORTANT: this uses ld.winnerSide (sourced from the API's authoritative
  // score.winner field) rather than comparing scoreHome/scoreAway directly.
  // Knockout matches that are level after 90 minutes get decided by extra
  // time and/or penalties — fullTime stays level (e.g. 1-1) even though
  // there IS a winner. Comparing raw scores would return null forever and
  // the bracket would never advance that team to the next round. The API's
  // winner field is correct in all cases (regular time, ET, or penalties).
  function _winnerOf(matchId) {
    const r = _result(matchId);
    if (!r) return null;
    const { fixture: f, ld } = r;
    const resolvedF = resolve(f); // recursive — winner of an R16 game needs its own slots resolved first

    if (ld.winnerSide === 'home') return resolvedF.home;
    if (ld.winnerSide === 'away') return resolvedF.away;

    // Fallback for older cached data without winnerSide: compare scores
    // (only correct for matches decided in regular time).
    if (ld.scoreHome > ld.scoreAway) return resolvedF.home;
    if (ld.scoreAway > ld.scoreHome) return resolvedF.away;
    return null;
  }

  function _loserOf(matchId) {
    const r = _result(matchId);
    if (!r) return null;
    const { fixture: f, ld } = r;
    const resolvedF = resolve(f);

    if (ld.winnerSide === 'home') return resolvedF.away;
    if (ld.winnerSide === 'away') return resolvedF.home;

    if (ld.scoreHome > ld.scoreAway) return resolvedF.away;
    if (ld.scoreAway > ld.scoreHome) return resolvedF.home;
    return null;
  }

  /* ── Placeholder parsers ────────────────────────────────────────────────
     Each parser recognises one placeholder "shape" used in FIXTURES_RAW
     and returns the resolved team name, or null if not yet knowable. */

  function _resolvePlaceholder(text) {
    if (!text) return null;

    let m;

    // "1st Group C" / "2nd Group C"
    m = text.match(/^(1st|2nd)\s+Group\s+([A-L])$/);
    if (m) {
      const results = _allGroupResults();
      const g = results[m[2]];
      if (!g) return null;
      return m[1] === '1st' ? g.first : g.second;
    }

    // "Best 3rd (A/B/C/D/F)" — slot identified by which R32 match it's in,
    // not by parsing the letter list (the letter list is just a hint to
    // the reader of which groups COULD feed this slot before qualification
    // is locked in). We match by matchId instead — see resolve().

    // "Winner R32 Match 76" / "Winner R16 Match 90" / "Winner QF Match 97" / "Winner SF Match 101"
    m = text.match(/^Winner\s+(?:R32|R16|QF|SF)\s+Match\s+(\d+)$/);
    if (m) return _winnerOf(Number(m[1]));

    // "Loser SF Match 101"
    m = text.match(/^Loser\s+SF\s+Match\s+(\d+)$/);
    if (m) return _loserOf(Number(m[1]));

    return null;
  }

  // Special-cased: "Best 3rd (...)" placeholders are resolved by knowing
  // which R32 match (by id) the slot belongs to, via SLOT_MATCH_ID.
  const MATCH_ID_TO_SLOT_GROUP = {}; // matchId -> winner-group letter (A,B,D,E,G,I,K,L)
  Object.keys(SLOT_MATCH_ID).forEach(letter => { MATCH_ID_TO_SLOT_GROUP[SLOT_MATCH_ID[letter]] = letter; });

  function _resolveBestThird(fixtureId) {
    const winnerGroupLetter = MATCH_ID_TO_SLOT_GROUP[fixtureId];
    if (!winnerGroupLetter) return null;
    const slots = _bestThirdSlots();
    if (!slots) return null;
    const sourceGroup = slots.slotMap[winnerGroupLetter];
    return slots.teamByGroup[sourceGroup] || null;
  }

  /* ── Public: resolve() ───────────────────────────────────────────────── */

  // In-flight guard against pathological circular references (shouldn't
  // happen with this bracket, but keeps things safe if data.js is edited).
  const _resolving = new Set();

  function resolve(fixture) {
    if (fixture.stage === 'group') {
      return { home: fixture.home, away: fixture.away, homeDesc: fixture.homeDesc || '', awayDesc: fixture.awayDesc || '' };
    }

    if (_resolving.has(fixture.id)) {
      return { home: fixture.home, away: fixture.away, homeDesc: fixture.homeDesc || '', awayDesc: fixture.awayDesc || '' };
    }
    _resolving.add(fixture.id);

    let home, away;
    try {
      home = fixture.home.startsWith('Best 3rd')
        ? _resolveBestThird(fixture.id)
        : _resolvePlaceholder(fixture.home);
      away = fixture.away.startsWith('Best 3rd')
        ? _resolveBestThird(fixture.id)
        : _resolvePlaceholder(fixture.away);
    } finally {
      _resolving.delete(fixture.id);
    }

    const dHome = home ? I18n.teamName(home) : fixture.home;
    const dAway = away ? I18n.teamName(away) : fixture.away;

    return {
      home: dHome,
      away: dAway,
      // Once a side is resolved, its hint/tooltip text is no longer needed
      homeDesc: home ? '' : (fixture.homeDesc || ''),
      awayDesc: away ? '' : (fixture.awayDesc || ''),
      homeResolved: !!home,
      awayResolved: !!away,
    };
  }

  // Call this after any live-data update (Live.onUpdate) so cached group
  // results / best-3rd rankings are recomputed against the latest scores.
  function invalidate() {
    _groupResultCache = null;
    _bestThirdCache = undefined;
  }

  return { resolve, invalidate };
